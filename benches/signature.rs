//! Criterion baseline for the verification-only Ed25519 boundary.

use criterion::{Criterion, black_box, criterion_group, criterion_main};
use crypt_io::signature::{Ed25519PublicKey, Ed25519Signature, verify_ed25519_detached};

const PUBLIC_KEY: Ed25519PublicKey = Ed25519PublicKey::new([
    0x3d, 0x40, 0x17, 0xc3, 0xe8, 0x43, 0x89, 0x5a, 0x92, 0xb7, 0x0a, 0xa7, 0x4d, 0x1b, 0x7e, 0xbc,
    0x9c, 0x98, 0x2c, 0xcf, 0x2e, 0xc4, 0x96, 0x8c, 0xc0, 0xcd, 0x55, 0xf1, 0x2a, 0xf4, 0x66, 0x0c,
]);
const SIGNATURE: Ed25519Signature = Ed25519Signature::new([
    0x92, 0xa0, 0x09, 0xa9, 0xf0, 0xd4, 0xca, 0xb8, 0x72, 0x0e, 0x82, 0x0b, 0x5f, 0x64, 0x25, 0x40,
    0xa2, 0xb2, 0x7b, 0x54, 0x16, 0x50, 0x3f, 0x8f, 0xb3, 0x76, 0x22, 0x23, 0xeb, 0xdb, 0x69, 0xda,
    0x08, 0x5a, 0xc1, 0xe4, 0x3e, 0x15, 0x99, 0x6e, 0x45, 0x8f, 0x36, 0x13, 0xd0, 0xf1, 0x1d, 0x8c,
    0x38, 0x7b, 0x2e, 0xae, 0xb4, 0x30, 0x2a, 0xee, 0xb0, 0x0d, 0x29, 0x16, 0x12, 0xbb, 0x0c, 0x00,
]);

fn require_valid_signature(result: crypt_io::signature::Result<()>) {
    if result.is_err() {
        std::process::abort();
    }
}

fn signature_benchmark(criterion: &mut Criterion) {
    criterion.bench_function("ed25519_verify_strict/rfc8032_one_byte", |bencher| {
        bencher.iter(|| {
            require_valid_signature(verify_ed25519_detached(
                black_box(&PUBLIC_KEY),
                black_box(b"\x72"),
                black_box(&SIGNATURE),
            ));
        });
    });
}

criterion_group!(benches, signature_benchmark);
criterion_main!(benches);
