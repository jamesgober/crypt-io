"""Generate tests/data/verify_vectors.rs from published verification vectors.

Usage:
    python -I tests/data/gen_verify_vectors.py SigVer15_186-3.rsp rfc8463.txt \
        rsa_signature_2048_sha256_test.json rsa_signature_3072_sha256_test.json \
        rsa_signature_4096_sha256_test.json ed25519_test.json tests/data/verify_vectors.rs

Inputs:
- SigVer15_186-3.rsp from NIST CAVP
  https://csrc.nist.gov/CSRC/media/Projects/Cryptographic-Algorithm-Validation-Program/documents/dss/186-3rsatestvectors.zip
- https://www.rfc-editor.org/rfc/rfc8463.txt
- Wycheproof (C2SP), testvectors_v1/: rsa_signature_{2048,3072,4096}_sha256_test.json,
  ed25519_test.json  https://github.com/C2SP/wycheproof
"""
import base64
import hashlib
import json
import re
import sys

sigver, rfc8463, w2048, w3072, w4096, wed, out_path = sys.argv[1:8]


def der_len(n):
    if n < 0x80:
        return bytes([n])
    b = n.to_bytes((n.bit_length() + 7) // 8, "big")
    return bytes([0x80 | len(b)]) + b


def der(tag, content):
    return bytes([tag]) + der_len(len(content)) + content


def der_int(v):
    b = v.to_bytes(max(1, (v.bit_length() + 7) // 8), "big")
    if b[0] & 0x80:
        b = b"\x00" + b
    return der(0x02, b)


RSA_ALG = der(0x30, der(0x06, bytes.fromhex("2a864886f70d010101")) + der(0x05, b""))


def spki(n, e):
    return der(0x30, RSA_ALG + der(0x03, b"\x00" + der(0x30, der_int(n) + der_int(e))))


SHA256_PREFIX = bytes.fromhex("3031300d060960864801650304020105000420")


def pkcs1v15_ok(n, e, msg, sig):
    k = (n.bit_length() + 7) // 8
    s = int.from_bytes(sig, "big")
    if len(sig) != k or s >= n:
        return False
    em = pow(s, e, n).to_bytes(k, "big")
    t = SHA256_PREFIX + hashlib.sha256(msg).digest()
    return em == b"\x00\x01" + b"\xff" * (k - len(t) - 3) + b"\x00" + t


# ---------------------------------------------------------------- NIST SigVer15
nist = []
mod = n = None
case = {}
for line in open(sigver, encoding="ascii"):
    line = line.strip()
    m = re.match(r"\[mod = (\d+)\]", line)
    if m:
        mod = int(m.group(1))
        continue
    if "=" not in line or line.startswith("#"):
        continue
    k, v = [x.strip() for x in line.split("=", 1)]
    if k == "n":
        n = int(v, 16)
    elif k == "SHAAlg":
        case = {"alg": v}
    elif k in ("e", "Msg", "S"):
        case[k] = v
    elif k == "Result":
        case["pass"] = v.startswith("P")
        if case["alg"] == "SHA256" and mod in (1024, 2048, 3072):
            e = int(case["e"], 16)
            # The file drops leading zero digits: S is modulus-sized and
            # every SigVer15 message is 128 bytes. A wrong pad would fail
            # the S^e mod n check below.
            case["S"] = case["S"].zfill(2 * ((mod + 7) // 8))
            case["Msg"] = case["Msg"].zfill(256)
            msg, sig = bytes.fromhex(case["Msg"]), bytes.fromhex(case["S"])
            # Independent check: the published verdict matches S^e mod n.
            assert pkcs1v15_ok(n, e, msg, sig) == case["pass"], (mod, case)
            nist.append((mod, spki(n, e).hex(), case["Msg"], case["S"], case["pass"]))
counts = {}
for c in nist:
    counts[c[0]] = counts.get(c[0], 0) + 1
assert counts == {1024: 18, 2048: 18, 3072: 18}, counts

# ---------------------------------------------------------------- RFC 8463
t = open(rfc8463, encoding="ascii").read()
ed_pub = base64.b64decode(re.search(r'p=(11qY[^"]+)"', t).group(1))
rsa_p = re.search(r'k=rsa; p=(.*?)"\)', t, re.S).group(1)
rsa_spki = base64.b64decode("".join(re.findall(r'[A-Za-z0-9+/=]+', rsa_p.replace('"', " "))))
sigs = re.findall(r"b=([A-Za-z0-9+/=\s]+?)(?:\n   [A-Z]|\n   From:)", t)
assert len(sigs) == 2, sigs
ed_sig = base64.b64decode("".join(sigs[0].split()))
rsa_sig = base64.b64decode("".join(sigs[1].split()))
assert len(ed_sig) == 64 and len(rsa_sig) == 128

# ------------------------------------------------------------------ Wycheproof
def wyche_rsa(path, keep_invalid):
    j = json.load(open(path, encoding="utf-8"))
    groups = []
    for g in j["testGroups"]:
        assert g["sha"] == "SHA-256", g["sha"]
        tests = [
            (tc["tcId"], tc["msg"], tc["sig"], tc["result"])
            for tc in g["tests"]
            if keep_invalid or tc["result"] != "invalid"
        ]
        groups.append((g["keySize"], g["publicKeyDer"], tests))
    return groups


def wyche_ed(path):
    j = json.load(open(path, encoding="utf-8"))
    groups = []
    for g in j["testGroups"]:
        groups.append((g["publicKey"]["pk"], [(tc["tcId"], tc["msg"], tc["sig"], tc["result"]) for tc in g["tests"]]))
    return groups


rsa_groups = wyche_rsa(w2048, True) + wyche_rsa(w3072, False) + wyche_rsa(w4096, False)
ed_groups = wyche_ed(wed)


def s(x):
    return '"' + x + '"'


o = [
    "// Generated by gen_verify_vectors.py from published vectors. Do not edit.",
    "//",
    "// - NIST CAVP SigVer15_186-3.rsp: every SHA256 case for [mod = 1024],",
    "//   [mod = 2048] and [mod = 3072], with its P/F verdict (each verdict was",
    "//   re-derived with S^e mod n before it was written here).",
    "// - RFC 8463 appendix A: both DKIM-Signature b= values and p= keys.",
    "// - Wycheproof (C2SP) rsa_signature_2048_sha256_test.json (all cases),",
    "//   the 3072 and 4096 files (valid and acceptable cases), and",
    "//   ed25519_test.json (all cases).",
    "",
    "#![allow(dead_code)]",
    "",
    "/// (modulus bits, SPKI hex, message hex, signature hex, verdict)",
    "pub const NIST_SIGVER15_SHA256: &[(u32, &str, &str, &str, bool)] = &[",
]
for bits, k, m, sg, ok in nist:
    o.append(f"    ({bits}, {s(k)}, {s(m)}, {s(sg)}, {str(ok).lower()}),")
o += [
    "];",
    "",
    f"pub const RFC8463_ED25519_PUBLIC_KEY: &str = {s(ed_pub.hex())};",
    f"pub const RFC8463_ED25519_SIGNATURE: &str = {s(ed_sig.hex())};",
    f"pub const RFC8463_RSA_1024_SPKI: &str = {s(rsa_spki.hex())};",
    f"pub const RFC8463_RSA_SIGNATURE: &str = {s(rsa_sig.hex())};",
    "",
    "pub struct WycheRsaGroup {",
    "    pub bits: u32,",
    "    pub spki: &'static str,",
    "    /// (tcId, message hex, signature hex, \"valid\" | \"acceptable\" | \"invalid\")",
    "    pub tests: &'static [(u32, &'static str, &'static str, &'static str)],",
    "}",
    "",
    "pub const WYCHEPROOF_RSA_PKCS1_SHA256: &[WycheRsaGroup] = &[",
]
for bits, k, tests in rsa_groups:
    o.append("    WycheRsaGroup {")
    o.append(f"        bits: {bits},")
    o.append(f"        spki: {s(k)},")
    o.append("        tests: &[")
    for tc, m, sg, r in tests:
        o.append(f"            ({tc}, {s(m)}, {s(sg)}, {s(r)}),")
    o.append("        ],")
    o.append("    },")
o += [
    "];",
    "",
    "pub struct WycheEd25519Group {",
    "    pub public_key: &'static str,",
    "    /// (tcId, message hex, signature hex, \"valid\" | \"acceptable\" | \"invalid\")",
    "    pub tests: &'static [(u32, &'static str, &'static str, &'static str)],",
    "}",
    "",
    "pub const WYCHEPROOF_ED25519: &[WycheEd25519Group] = &[",
]
for pk, tests in ed_groups:
    o.append("    WycheEd25519Group {")
    o.append(f"        public_key: {s(pk)},")
    o.append("        tests: &[")
    for tc, m, sg, r in tests:
        o.append(f"            ({tc}, {s(m)}, {s(sg)}, {s(r)}),")
    o.append("        ],")
    o.append("    },")
o += ["];", ""]
open(out_path, "w", encoding="ascii", newline="\n").write("\n".join(o))
print("ok nist", counts, "wycheproof rsa groups", len(rsa_groups),
      "tests", sum(len(g[2]) for g in rsa_groups), "ed25519 groups", len(ed_groups),
      "tests", sum(len(g[1]) for g in ed_groups))
