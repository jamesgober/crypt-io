"""Generate tests/data/pbkdf2_grid.rs with Python's hashlib.pbkdf2_hmac.

Usage: python -I tests/data/gen_pbkdf2_grid.py tests/data/pbkdf2_grid.rs
"""
import base64
import hashlib
import hmac
import sys

out_path = sys.argv[1]


def pattern(n, seed):
    return bytes((seed * 31 + i * 7) % 256 for i in range(n))


cases = []
pw_lens = [0, 1, 31, 63, 64, 65, 128, 129]
salt_lens = [0, 1, 16, 55, 56, 64, 119, 120]
iters = [1, 2, 3, 17, 1000]
out_lens = [1, 16, 31, 32, 33, 64, 65, 100]
i = 0
for pl in pw_lens:
    for sl in salt_lens:
        it = iters[i % len(iters)]
        ol = out_lens[i % len(out_lens)]
        pw = pattern(pl, 1 + i)
        salt = pattern(sl, 101 + i)
        dk = hashlib.pbkdf2_hmac("sha256", pw, salt, it, ol)
        cases.append((pw.hex(), salt.hex(), it, dk.hex()))
        i += 1

# RFC 7677 section 3 (SCRAM-SHA-256 example).
password = b"pencil"
salt = base64.b64decode("W22ZaJ0SNY7soEsUEjb6gQ==")
auth = (
    b"n=user,r=rOprNGfwEbeRWgbNEkqO,"
    b"r=rOprNGfwEbeRWgbNEkqO%hvYDpWUa2RaTCAfuxFIlj)hNlF$k0,s=W22ZaJ0SNY7soEsUEjb6gQ==,i=4096,"
    b"c=biws,r=rOprNGfwEbeRWgbNEkqO%hvYDpWUa2RaTCAfuxFIlj)hNlF$k0"
)
salted = hashlib.pbkdf2_hmac("sha256", password, salt, 4096, 32)
client_key = hmac.new(salted, b"Client Key", "sha256").digest()
stored_key = hashlib.sha256(client_key).digest()
client_sig = hmac.new(stored_key, auth, "sha256").digest()
proof = bytes(a ^ b for a, b in zip(client_key, client_sig))
server_key = hmac.new(salted, b"Server Key", "sha256").digest()
server_sig = hmac.new(server_key, auth, "sha256").digest()
assert base64.b64encode(proof) == b"dHzbZapWIk4jUhN+Ute9ytag9zjfMHgsqmmiz7AndVQ="
assert base64.b64encode(server_sig) == b"6rriTRBi23WpRR/wtup+mMhUZUn/dB5nLTJRsjl95G4="

o = [
    "// Generated by gen_pbkdf2_grid.py with Python's hashlib.pbkdf2_hmac",
    "// (OpenSSL-backed, independent of crypt-io). Do not edit.",
    "",
    "#![allow(dead_code)]",
    "",
    "/// (password hex, salt hex, iterations, derived key hex)",
    "pub const GRID: &[(&str, &str, u32, &str)] = &[",
]
for pw, s, it, dk in cases:
    o.append(f'    ("{pw}", "{s}", {it}, "{dk}"),')
o += [
    "];",
    "",
    "/// RFC 7677 section 3: SaltedPassword for \"pencil\", the example salt and",
    "/// i=4096 (checked against the RFC's ClientProof and ServerSignature).",
    f'pub const SCRAM_SALTED_PASSWORD: &str = "{salted.hex()}";',
    f'pub const SCRAM_SALT: &str = "{salt.hex()}";',
    f'pub const SCRAM_AUTH_MESSAGE: &str = "{auth.decode()}";',
    f'pub const SCRAM_CLIENT_PROOF: &str = "{proof.hex()}";',
    f'pub const SCRAM_SERVER_SIGNATURE: &str = "{server_sig.hex()}";',
    "",
]
open(out_path, "w", encoding="ascii", newline="\n").write("\n".join(o))
print("ok", len(cases), "grid cases")
