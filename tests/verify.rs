//! Signature checks (`Ed25519PublicKey`, `RsaPublicKey`) against
//! published vectors.
//!
//! - RSA: every SHA-256 case of NIST CAVP SigVer15 (FIPS 186-3,
//!   PKCS#1 v1.5) for 1024-, 2048- and 3072-bit keys, with NIST's pass /
//!   fail verdicts; Wycheproof's 2048-bit PKCS#1 v1.5 SHA-256 file (BER
//!   padding, wrong hashes, missing NULL, malleability and more) and the
//!   valid cases of its 3072 and 4096 files.
//! - Ed25519: all of Wycheproof's `ed25519_test.json` (non-canonical
//!   `S`, small-order and mixed-order keys, truncated signatures, ...).
//! - DKIM: both signatures of the RFC 8463 example message, checked
//!   against the RFC's `p=` keys.
//!
//! `valid` must pass and `invalid` must fail (at parse or at check).
//! Wycheproof's `acceptable` cases may go either way; the counts are
//! printed so a backend change is visible in the test log.
//!
//! `tests/data/verify_vectors.rs` is generated by
//! `tests/data/gen_verify_vectors.py`.

#![cfg(any(feature = "sign-ed25519", feature = "sign-rsa"))]
#![allow(clippy::unwrap_used, clippy::expect_used)]

#[path = "data/verify_vectors.rs"]
mod vectors;

use crypt_io::Error;

fn h(s: &str) -> Vec<u8> {
    hex::decode(s).expect("valid hex")
}

/// RFC 8463 A.3: the relaxed-canonical header data (RFC 6376 section
/// 3.4.2) a DKIM-Signature with selector `s` and algorithm `a` signs,
/// with its own `b=` value empty.
#[cfg(feature = "hash-sha2")]
fn rfc8463_signed_headers(a: &str, s: &str) -> String {
    format!(
        concat!(
            "from:Joe SixPack <joe@football.example.com>\r\n",
            "to:Suzie Q <suzie@shopping.example.net>\r\n",
            "subject:Is dinner ready?\r\n",
            "date:Fri, 11 Jul 2003 21:00:37 -0700 (PDT)\r\n",
            "message-id:<20030712040037.46341.5F8J@football.example.com>\r\n",
            "dkim-signature:v=1; a={}; c=relaxed/relaxed; ",
            "d=football.example.com; i=@football.example.com; q=dns/txt; ",
            "s={}; t=1528637909; ",
            "h=from : to : subject : date : message-id : from : subject : date; ",
            "bh=2jUSOH9NhtVGCQWNr9BrIAPreKQjO6Sn7XIkfJVOzv8=; b=",
        ),
        a, s
    )
}

#[cfg(feature = "sign-ed25519")]
mod ed25519 {
    use super::{Error, h, vectors};
    use crypt_io::sign::{Ed25519PublicKey, Ed25519SigningKey};

    fn key(hex: &str) -> crypt_io::Result<Ed25519PublicKey> {
        let bytes: [u8; 32] = h(hex).try_into().unwrap();
        Ed25519PublicKey::from_bytes(&bytes)
    }

    #[test]
    fn wycheproof_ed25519() {
        let (mut valid, mut invalid, mut acceptable_ok, mut acceptable_err) = (0, 0, 0, 0);
        for group in vectors::WYCHEPROOF_ED25519 {
            let parsed = key(group.public_key);
            for &(id, message, signature, result) in group.tests {
                let outcome = parsed
                    .as_ref()
                    .map_err(Clone::clone)
                    .and_then(|k| k.check(&h(message), &h(signature)));
                match result {
                    "valid" => {
                        assert_eq!(outcome, Ok(()), "tcId {id}");
                        valid += 1;
                    }
                    "invalid" => {
                        assert!(outcome.is_err(), "tcId {id} accepted");
                        invalid += 1;
                    }
                    _ if outcome.is_ok() => acceptable_ok += 1,
                    _ => acceptable_err += 1,
                }
            }
        }
        println!(
            "ed25519: {valid} valid ok, {invalid} invalid rejected, \
             acceptable: {acceptable_ok} accepted / {acceptable_err} rejected"
        );
        assert!(valid > 0 && invalid > 0);
    }

    #[test]
    fn a_bad_signature_is_authentication_failed() {
        let signing = Ed25519SigningKey::from_seed(&[5u8; 32]).unwrap();
        let public = Ed25519PublicKey::from_bytes(&signing.public_key()).unwrap();
        let mut sig = signing.sign(b"m");
        public.check(b"m", &sig).unwrap();
        assert_eq!(public.check(b"n", &sig), Err(Error::AuthenticationFailed));
        assert_eq!(
            public.check(b"m", &sig[..63]),
            Err(Error::AuthenticationFailed)
        );
        assert_eq!(
            public.check(b"m", &[0u8; 65]),
            Err(Error::AuthenticationFailed)
        );
        assert_eq!(public.check(b"m", &[]), Err(Error::AuthenticationFailed));
        sig[63] ^= 0x40;
        assert_eq!(public.check(b"m", &sig), Err(Error::AuthenticationFailed));
    }

    #[test]
    fn another_key_does_not_verify() {
        let a = Ed25519SigningKey::from_seed(&[1u8; 32]).unwrap();
        let b = Ed25519PublicKey::from_bytes(
            &Ed25519SigningKey::from_seed(&[2u8; 32])
                .unwrap()
                .public_key(),
        )
        .unwrap();
        assert_eq!(
            b.check(b"m", &a.sign(b"m")),
            Err(Error::AuthenticationFailed)
        );
    }

    #[test]
    fn public_key_accessors() {
        let pk = h(vectors::RFC8463_ED25519_PUBLIC_KEY);
        let k = key(vectors::RFC8463_ED25519_PUBLIC_KEY).unwrap();
        assert_eq!(k.to_bytes().as_slice(), pk);
        assert_eq!(k.clone(), k);
        assert_eq!(
            format!("{k:?}"),
            format!("Ed25519PublicKey({})", vectors::RFC8463_ED25519_PUBLIC_KEY)
        );
        fn send_sync<T: Send + Sync>() {}
        send_sync::<Ed25519PublicKey>();
    }

    #[cfg(feature = "hash-sha2")]
    #[test]
    fn rfc8463_dkim_ed25519_signature_checks() {
        let k = key(vectors::RFC8463_ED25519_PUBLIC_KEY).unwrap();
        let data = super::rfc8463_signed_headers("ed25519-sha256", "brisbane");
        let hash = crypt_io::hash::sha256(data.as_bytes());
        k.check(&hash, &h(vectors::RFC8463_ED25519_SIGNATURE))
            .unwrap();
        // One byte of the header data changed.
        let other = crypt_io::hash::sha256(data.replace("dinner", "Dinner").as_bytes());
        assert_eq!(
            k.check(&other, &h(vectors::RFC8463_ED25519_SIGNATURE)),
            Err(Error::AuthenticationFailed)
        );
    }
}

#[cfg(feature = "sign-rsa")]
mod rsa {
    use super::{Error, h, vectors};
    use crypt_io::sign::{RSA_MIN_MODULUS_BITS_LEGACY, RsaPublicKey, RsaSigningKey};

    #[test]
    fn nist_sigver15_sha256_verdicts() {
        for (i, &(bits, spki, message, signature, pass)) in
            vectors::NIST_SIGVER15_SHA256.iter().enumerate()
        {
            let parsed = if bits < 2048 {
                RsaPublicKey::from_der_allow_1024(&h(spki))
            } else {
                RsaPublicKey::from_der(&h(spki))
            };
            let outcome = parsed.and_then(|k| {
                assert_eq!(k.modulus_bits(), bits);
                k.check_pkcs1v15_sha256(&h(message), &h(signature))
            });
            if pass {
                assert_eq!(outcome, Ok(()), "case {i} ({bits} bits) should pass");
            } else {
                assert!(outcome.is_err(), "case {i} ({bits} bits) should fail");
            }
        }
    }

    #[test]
    fn wycheproof_rsa_pkcs1_sha256() {
        let (mut valid, mut invalid, mut acceptable_ok, mut acceptable_err) = (0, 0, 0, 0);
        for group in vectors::WYCHEPROOF_RSA_PKCS1_SHA256 {
            let parsed = RsaPublicKey::from_der(&h(group.spki));
            for &(id, message, signature, result) in group.tests {
                let outcome = parsed
                    .as_ref()
                    .map_err(Clone::clone)
                    .and_then(|k| k.check_pkcs1v15_sha256(&h(message), &h(signature)));
                match result {
                    "valid" => {
                        assert_eq!(outcome, Ok(()), "{} bits tcId {id}", group.bits);
                        valid += 1;
                    }
                    "invalid" => {
                        assert!(outcome.is_err(), "{} bits tcId {id} accepted", group.bits);
                        invalid += 1;
                    }
                    _ if outcome.is_ok() => acceptable_ok += 1,
                    _ => acceptable_err += 1,
                }
            }
        }
        println!(
            "rsa: {valid} valid ok, {invalid} invalid rejected, \
             acceptable: {acceptable_ok} accepted / {acceptable_err} rejected"
        );
        assert!(valid > 0 && invalid > 200);
    }

    #[test]
    fn rfc8463_1024_bit_key_needs_the_legacy_constructor() {
        let spki = h(vectors::RFC8463_RSA_1024_SPKI);
        assert_eq!(
            RsaPublicKey::from_der(&spki).unwrap_err(),
            Error::Sign("key rejected: RSA modulus smaller than 2048 bits")
        );
        let k = RsaPublicKey::from_der_allow_1024(&spki).unwrap();
        assert_eq!(k.modulus_bits(), 1024);
        assert_eq!(RSA_MIN_MODULUS_BITS_LEGACY, 1024);
    }

    #[cfg(feature = "hash-sha2")]
    #[test]
    fn rfc8463_dkim_rsa_signature_checks() {
        let k = RsaPublicKey::from_der_allow_1024(&h(vectors::RFC8463_RSA_1024_SPKI)).unwrap();
        let data = super::rfc8463_signed_headers("rsa-sha256", "test");
        k.check_pkcs1v15_sha256(data.as_bytes(), &h(vectors::RFC8463_RSA_SIGNATURE))
            .unwrap();
        assert_eq!(
            k.check_pkcs1v15_sha256(
                data.replace("s=test", "s=tesT").as_bytes(),
                &h(vectors::RFC8463_RSA_SIGNATURE)
            ),
            Err(Error::AuthenticationFailed)
        );
    }

    #[test]
    fn signing_key_output_checks_with_its_spki_and_pkcs1() {
        let generated =
            aws_lc_rs::rsa::KeyPair::generate(aws_lc_rs::rsa::KeySize::Rsa2048).unwrap();
        let pkcs8 =
            aws_lc_rs::encoding::AsDer::<aws_lc_rs::encoding::Pkcs8V1Der>::as_der(&generated)
                .unwrap();
        let signing = RsaSigningKey::from_pkcs8_der(pkcs8.as_ref()).unwrap();
        let sig = signing.sign_pkcs1v15_sha256(b"payload").unwrap();

        let from_spki = RsaPublicKey::from_der(signing.public_key_der()).unwrap();
        from_spki.check_pkcs1v15_sha256(b"payload", &sig).unwrap();

        // The same key as a bare PKCS#1 RSAPublicKey.
        let pkcs1 = aws_lc_rs::signature::KeyPair::public_key(&generated)
            .as_ref()
            .to_vec();
        let from_pkcs1 = RsaPublicKey::from_der(&pkcs1).unwrap();
        from_pkcs1.check_pkcs1v15_sha256(b"payload", &sig).unwrap();
        assert_eq!(from_pkcs1.modulus_bits(), 2048);

        let mut bad = sig.clone();
        bad[0] ^= 1;
        assert_eq!(
            from_spki.check_pkcs1v15_sha256(b"payload", &bad),
            Err(Error::AuthenticationFailed)
        );
        assert_eq!(
            from_spki.check_pkcs1v15_sha256(b"payload", &sig[1..]),
            Err(Error::AuthenticationFailed)
        );
        assert_eq!(
            from_spki.check_pkcs1v15_sha256(b"other", &sig),
            Err(Error::AuthenticationFailed)
        );
    }

    #[test]
    fn garbage_is_a_key_error_not_an_auth_failure() {
        for der in [&b""[..], b"\x30\x00", b"not a key"] {
            assert!(matches!(RsaPublicKey::from_der(der), Err(Error::Sign(_))));
            assert!(matches!(
                RsaPublicKey::from_der_allow_1024(der),
                Err(Error::Sign(_))
            ));
        }
        // An Ed25519 SPKI is not an RSA key.
        let ed_spki = h(
            "302a300506032b6570032100d75a980182b10ab7d54bfed3c964073a0ee172f3daa62325af021a68f707511a",
        );
        assert!(matches!(
            RsaPublicKey::from_der(&ed_spki),
            Err(Error::Sign(_))
        ));
    }

    #[test]
    fn public_key_traits() {
        let k = RsaPublicKey::from_der_allow_1024(&h(vectors::RFC8463_RSA_1024_SPKI)).unwrap();
        assert_eq!(format!("{k:?}"), "RsaPublicKey { modulus_bits: 1024, .. }");
        let _cloned = k.clone();
        fn send_sync<T: Send + Sync>() {}
        send_sync::<RsaPublicKey>();
    }
}
